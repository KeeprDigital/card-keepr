import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { createServer } from "node:http";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { executeSql, runCli } from "./acceptance-runtime.mjs";
import { validateDispatchAndWriteSql } from "../../scripts/production-release.mjs";
import { runFreshBaselineRelease } from "../../scripts/fresh-baseline-release.mjs";
import {
  handoffReadSql,
  renewHandoffSql,
  phaseSql,
  transferSql,
  destinationReleaseSql,
} from "../../scripts/fresh-baseline-handoff.mjs";
import {
  prepareCardSearchForD1ExportStatements,
  reconstructCardSearchAfterD1RestoreStatements,
} from "../../src/catalogue/backup-recovery/card-search-recovery-statements.ts";
import * as queries from "./query-helpers/fresh-baseline.mjs";

// Called only after native publication, owner identity decisions, verified SQL
// backup and current-plus-two retention have been generated by shipped Workflows.
// The source uses native D1 and the destination is an independent SQLite file.
// Publisher inputs, provider activation/observation and destination smoke are synthetic.
export async function proveNativePopulatedHandoff({
  t,
  directory,
  statePath,
  configPath,
  environment,
  sourceFile,
  consumer,
}) {
  const templatePath = join(directory, "fresh-template.sqlite");
  const template = new DatabaseSync(templatePath);
  for (const file of (await readdir("migrations")).filter((name) => name.endsWith(".sql")).sort())
    template.exec(await readFile(`migrations/${file}`, "utf8"));
  queries.lowerBaselineLevel(template);
  for (const sql of prepareCardSearchForD1ExportStatements) template.exec(sql);
  template.close();
  const baseline =
    execFileSync("/usr/bin/sqlite3", [templatePath, ".dump"], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 }) +
    "\n" +
    reconstructCardSearchAfterD1RestoreStatements.join(";\n") +
    ";";
  const statusResult = await runCli(["status", "--json"], environment);
  assert.equal(statusResult.code, 0, statusResult.stdout + statusResult.stderr);
  const status = JSON.parse(statusResult.stdout);
  assert.equal(status.release_preflight.bootstrap, false);
  assert.equal(status.release_preflight.retention_ready, true, JSON.stringify(status.release_preflight));
  assert.ok(status.release_preflight.smoke_targets, JSON.stringify(status.release_preflight));
  const targets = status.release_preflight.smoke_targets;
  for (const revision of targets.revisions) {
    for (const [kind, cursor, id, query] of [
      ["cards", revision.card_cursor, revision.card_id, ""],
      ["cards", revision.search_cursor, revision.card_id, `&q=${encodeURIComponent(revision.search_query)}`],
      ["printings", revision.printing_cursor, revision.printing_id, ""],
    ]) {
      const page = await consumer(`/v1/${kind}?after=${encodeURIComponent(cursor)}${query}`);
      assert.equal(page.status, 200, JSON.stringify(page));
      assert.equal(page.body.meta.catalogue_revision_id, revision.revision_id);
      assert.ok(page.body.data.some((record) => record.id === id));
    }
  }
  const image = await consumer(`/v1/printing-images/${encodeURIComponent(targets.printing_image_id)}/content`);
  assert.equal(image.status, 200);
  assert.ok(image.byte_length > 0);
  const stale = await consumer(`/v1/cards?after=${encodeURIComponent(targets.stale_cursor)}`);
  assert.equal(stale.status, 409);
  assert.equal(stale.body.code, "cursor_revision_unavailable");
  const dispatches = [];
  const github = createServer(async (req, res) => {
    let text = "";
    for await (const bytes of req) text += bytes;
    dispatches.push(JSON.parse(text));
    res.writeHead(204);
    res.end();
  });
  await new Promise((resolve) => github.listen(0, "127.0.0.1", resolve));
  t.after(() => new Promise((resolve) => github.close(resolve)));
  const owner = {
    ...environment,
    KEEPR_GITHUB_RELEASE_ACTOR: "native-owner[bot]",
    KEEPR_GITHUB_RELEASE_TOKEN: "synthetic-local-dispatch-token",
    KEEPR_GITHUB_API_URL: `http://127.0.0.1:${github.address().port}`,
  };
  const args = [
    "release",
    "production",
    "--release-id",
    "native_populated_fresh",
    "--expected-current-revision",
    status.safe_state.current_revision_id,
    "--expected-head-sha",
    "a".repeat(40),
    "--expected-migration-level",
    String(status.release_preflight.schema_migration_level),
    "--idempotency-key",
    "native_populated_prepare",
    "--environment",
    "production",
    "--fresh-database-id",
    "native_populated_destination",
    "--baseline-sha256",
    createHash("sha256").update(baseline).digest("hex"),
    "--yes",
    "--json",
  ];
  const preview = await runCli(args, owner);
  assert.equal(preview.code, 3, preview.stdout + preview.stderr);
  const confirmation = JSON.parse(preview.stdout).detail.slice("Confirmation must exactly equal ".length);
  const dispatched = await runCli([...args, "--confirm", confirmation], owner);
  assert.equal(dispatched.code, 10, dispatched.stdout + dispatched.stderr);
  const input = dispatches[0].inputs;
  const environmentSql = Object.fromEntries(Object.entries(input).map(([key, value]) => [key.toUpperCase(), value]));
  environmentSql.HANDOFF_EXECUTION_ID = "native_populated_execution";
  await validateDispatchAndWriteSql(environmentSql, directory);
  const source = new DatabaseSync(await sourceFile(), { readOnly: true });
  const destination = new DatabaseSync(join(directory, "fresh-destination.sqlite"));
  t.after(() => {
    source.close();
    destination.close();
  });
  const before = queries.retainedIdentityAndEvidence(source);
  assert.ok(before.decisions.length > 0);
  assert.ok(before.references.length > 0);
  const read = (role) => {
    if (role === "destination" && queries.schemaRows(destination).all().length === 0) return null;
    return (role === "source" ? source : destination).prepare(handoffReadSql(environmentSql, role)).get() ?? null;
  };
  const execute = async (role, sql) => {
    if (role === "source") {
      const path = join(directory, "native-handoff-step.sql");
      await writeFile(path, sql);
      await executeSql(statePath, path, configPath);
    } else {
      destination.exec("BEGIN");
      try {
        destination.exec(sql);
        destination.exec("COMMIT");
      } catch (error) {
        destination.exec("ROLLBACK");
        throw error;
      }
    }
  };
  const versions = [
    { worker: "card-keepr-api", version_id: "synthetic_native_api" },
    { worker: "card-keepr-ingestion", version_id: "synthetic_native_ingestion" },
  ];
  const result = await runFreshBaselineRelease(environmentSql, {
    read: async (role) => read(role),
    renew: async () => {
      for (const role of ["source", "destination"])
        if (read(role)) await execute(role, renewHandoffSql(environmentSql, role));
    },
    claim: async () => executeSql(statePath, join(directory, "fresh-claim.sql"), configPath),
    installBaseline: async () => {
      destination.exec(baseline);
      queries.assertBaselineIntegrity(destination);
      return {
        baseline_sha256: JSON.parse(input.prepared_plan_json).fresh_baseline_handoff.baseline_sha256,
        migration_level: 1,
        integrity: "ok",
        foreign_keys: "ok",
      };
    },
    transfer: async (row) => execute("destination", transferSql(environmentSql, row)),
    advance: async (role, from, evidence) => execute(role, phaseSql(environmentSql, role, from, evidence)),
    uploadAndVerify: async () => versions,
    activate: async () => {
      assert.equal(read("source").phase, 4);
      assert.equal(read("destination").phase, 4);
    },
    observe: async () => ({ synthetic_provider: true, versions, database_id: "native_populated_destination" }),
    smoke: async () => ({ synthetic_destination_smoke: true }),
    accept: async (row) => execute("destination", destinationReleaseSql(environmentSql, row)),
  });
  assert.equal(result.state, "handoff_accepted");
  assert.deepEqual(queries.retainedIdentityAndEvidence(source), before);
  assert.equal(read("source").phase, 6);
  assert.equal(read("destination").phase, 6);
  assert.equal((await consumer("/v1/cards?game=one-piece")).status, 200);
  const after = JSON.parse((await runCli(["status", "--json"], environment)).stdout);
  assert.equal(after.safe_state.mutation_safe, false);
  assert.equal(after.fresh_baseline_handoff.phase, 6);
  queries.mutateCatalogue(destination).run();
}
