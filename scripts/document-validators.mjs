#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { documentSchemas } from "../src/catalogue/shared/document-schemas.mjs";

const ajv = new Ajv({ code: { source: true, esm: true }, strict: true });
const exports = {};
for (const [name, schema] of Object.entries(documentSchemas)) {
  ajv.addSchema(schema, name);
  exports[name] = name;
}
const code = standaloneCode(ajv, exports);
const output = new URL("../src/catalogue/shared/document-validators.mjs", import.meta.url);
const generated = `// Generated by scripts/document-validators.mjs; edit document-schemas.mjs.\n${code}\n`;
const declarations = new URL("../src/catalogue/shared/document-validators.d.mts", import.meta.url);
const signatures = `// Generated validator signatures.\n${Object.keys(exports)
  .map((name) => `export function ${name}(value: unknown): boolean;`)
  .join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated || readFileSync(declarations, "utf8") !== signatures)
    throw new Error("Document validators are stale; run npm run documents:generate.");
} else {
  writeFileSync(output, generated);
  writeFileSync(declarations, signatures);
}
