#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv/dist/compile/codegen/index.js";
import { build } from "esbuild";
import addFormats from "ajv-formats";
import { fileURLToPath } from "node:url";

// Bundle the schema sources so their shared TypeScript profile registry is also
// the generator's source of truth, without a second handwritten schema copy.
const bundled = await build({
  entryPoints: [fileURLToPath(new URL("../src/catalogue/shared/document-schemas.mjs", import.meta.url))],
  bundle: true,
  platform: "node",
  format: "esm",
  write: false,
});
const { documentSchemas } = await import(
  `data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`
);

const ajv = new Ajv({ code: { source: true, esm: true, formats: _`formats` }, strict: true });
addFormats(ajv);
const exports = {};
for (const [name, schema] of Object.entries(documentSchemas)) {
  ajv.addSchema(schema, name);
  exports[name] = name;
}
const code = standaloneCode(ajv, exports);
const output = new URL("../src/catalogue/shared/document-validators.mjs", import.meta.url);
const generated = `// Generated by scripts/document-validators.mjs; edit document-schemas.mjs.\nimport { fullFormats as formats } from "ajv-formats/dist/formats.js";\n${code}\n`;
const declarations = new URL("../src/catalogue/shared/document-validators.d.mts", import.meta.url);
const signatures = `// Generated validator signatures.\n${Object.keys(exports)
  .map((name) => `export function ${name}(value: unknown): boolean;`)
  .join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated || readFileSync(declarations, "utf8") !== signatures)
    throw new Error("Document validators are stale; run npm run documents:generate.");
} else {
  writeFileSync(output, generated);
  writeFileSync(declarations, signatures);
}
